# STEP 3: Confusion Matrix + 5-Fold Cross Validation

import pandas as pd
import matplotlib.pyplot as plt

from sklearn.model_selection import StratifiedKFold, cross_validate
from sklearn.metrics import ConfusionMatrixDisplay
from sklearn.base import clone

# Create all six models
cv_models = {
    "Random Forest": rf_model,
    "Decision Tree": dt_model,
    "Naive Bayes": nb_model,
    "SVM": svm_model,
    "KNN": knn_model,
    "XGBoost": xgb_model
}

# 5-Fold Stratified Cross Validation
cv = StratifiedKFold(
    n_splits=5,
    shuffle=True,
    random_state=42
)

scoring = {
    "accuracy": "accuracy",
    "precision": "precision_weighted",
    "recall": "recall_weighted",
    "f1": "f1_weighted"
}

cv_results = []

for name, model in cv_models.items():

    print("\nModel:", name)

    # Cross-validation on training data only
    if name == "XGBoost":
        scores = cross_validate(
            clone(model), X_train, y_train_encoded,
            cv=cv, scoring=scoring
        )
        model.fit(X_train, y_train_encoded)
        pred = le.inverse_transform(
            model.predict(X_test).astype(int)
        )
    else:
        scores = cross_validate(
            clone(model), X_train, y_train,
            cv=cv, scoring=scoring
        )
        model.fit(X_train, y_train)
        pred = model.predict(X_test)

    # Save CV results
    cv_results.append({
        "Algorithm": name,
        "CV Accuracy (%)": scores["test_accuracy"].mean() * 100,
        "CV Precision (%)": scores["test_precision"].mean() * 100,
        "CV Recall (%)": scores["test_recall"].mean() * 100,
        "CV F1-Score (%)": scores["test_f1"].mean() * 100
    })

    # Generate confusion matrix on test data
    ConfusionMatrixDisplay.from_predictions(
        y_test, pred,
        xticks_rotation="vertical",
        cmap="Blues",
        colorbar=False
    )

    plt.title(name + " Confusion Matrix")
    plt.tight_layout()
    plt.savefig(
        name.replace(" ", "_") + "_confusion_matrix.png",
        dpi=300
    )
    plt.show()

# Display cross-validation comparison
cv_df = pd.DataFrame(cv_results)

print("\n5-FOLD CROSS VALIDATION RESULTS")
print(cv_df.round(2).to_string(index=False))

cv_df.to_csv("cross_validation_results.csv", index=False)

